"""Render canonical corpus markdown to DOCX, PDF and TXT (the formats the attack carriers need).

    python -m research.corpus.render <corpus_dir>      # writes <corpus_dir>/renders/<id>.<lang>.{docx,pdf,txt}

Understands the markdown this corpus uses: `#`/`##`/`###` headings, pipe tables, `- ` and `1. `
lists, `**bold**`, blank-line paragraphs with hard line breaks inside them. DOCX and PDF get
real formatting (tables, list styles, bold) but no words that are not in the source: no
letterhead, no page numbers, and the python-docx "generated by" comment is blanked, because
full extraction would hand it to the classifier. TXT is the canonical text unchanged.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import docx
from fpdf import FPDF

# fonts-dejavu-core in the image; the PDF core fonts have no Cyrillic
FONT_DIR = Path("/usr/share/fonts/truetype/dejavu")
BULLET = re.compile(r"^[-*] ")
NUMBERED = re.compile(r"^\d+\. ")
BOLD = re.compile(r"\*\*(.+?)\*\*")
HEADINGS = {"# ": "h1", "## ": "h2", "### ": "h3"}
# Official forms (П-2, 1ДР, declarations, power of attorney) are laid out as a grid of label/value cells,
# like the printed forms; the words stay exactly as in the source, only the spacing between fields goes.
FORM_PREFIX = "res_id_form_"
FIELD = re.compile(r"^([^:]{1,80}):\s+(\S.*)$")

Block = tuple[str, object]  # (kind, text | list of lines | table rows)


def _cells(line: str) -> list[str]:
    return [c.strip() for c in line.strip().strip("|").split("|")]


def _form_rows(lines: list[str]) -> list[list[str]]:
    """Each `Label: value` field (fields on a line are split by 2+ spaces) → a [label:, value] row;
    other text → a one-cell row. One field per row keeps cells wide enough that no word is split."""
    rows = []
    for ln in lines:
        for field in re.split(r"\s{2,}", ln.strip()):
            m = FIELD.match(field)
            rows.append([m.group(1) + ":", m.group(2)] if m else [field])
    return rows


def blocks(text: str, form: bool = False) -> list[Block]:
    """Markdown → [(kind, payload)], kind in h1, h2, h3, p, table, ul, ol (+ form for official forms)."""
    out: list[Block] = []
    for para in text.strip().split("\n\n"):
        para = para.strip("\n")
        lines = para.split("\n")
        head = next((k for p, k in HEADINGS.items() if para.startswith(p)), None)
        if head and len(lines) == 1:
            out.append((head, para.split(" ", 1)[1].strip()))
        elif all(ln.lstrip().startswith("|") for ln in lines):
            rows = [_cells(ln) for ln in lines if not set(ln.strip()) <= set("|-: ")]
            out.append(("table", rows))
        elif all(BULLET.match(ln) for ln in lines):
            out.append(("ul", [ln[2:].strip() for ln in lines]))
        elif all(NUMBERED.match(ln) for ln in lines):
            out.append(("ol", [ln.strip() for ln in lines]))  # keep the source's own numbers
        elif form and any(FIELD.match(f) for ln in lines for f in re.split(r"\s{2,}", ln.strip())):
            out.append(("form", _form_rows(lines)))
        else:
            out.append(("p", para.strip()))
    return out


def _segments(text: str) -> list[tuple[str, bool]]:
    """'a **b** c' → [('a ', False), ('b', True), (' c', False)]."""
    parts, pos = [], 0
    for m in BOLD.finditer(text):
        if m.start() > pos:
            parts.append((text[pos : m.start()], False))
        parts.append((m.group(1), True))
        pos = m.end()
    if pos < len(text):
        parts.append((text[pos:], False))
    return parts


def to_txt(text: str) -> str:
    return text.strip() + "\n"


def _docx_runs(par: docx.text.paragraph.Paragraph, text: str, bold: bool = False) -> None:
    for i, line in enumerate(text.split("\n")):
        if i:
            par.add_run().add_break()
        for seg, b in _segments(line):
            par.add_run(seg).bold = bold or b


def to_docx(bl: list[Block], path: Path) -> None:
    d = docx.Document()
    d.core_properties.comments = ""  # python-docx default: "generated by python-docx"
    d.core_properties.author = ""
    for kind, payload in bl:
        if kind in ("h1", "h2", "h3"):
            d.add_heading(str(payload), level=int(kind[1]))
        elif kind == "table":
            rows = payload  # type: ignore[assignment]
            width = max(len(r) for r in rows)  # type: ignore[attr-defined]
            table = d.add_table(rows=0, cols=width)
            table.style = "Table Grid"
            for i, row in enumerate(rows):  # type: ignore[attr-defined]
                cells = table.add_row().cells
                for cell, value in zip(cells, row, strict=False):
                    _docx_runs(cell.paragraphs[0], value, bold=i == 0)
        elif kind == "form":
            rows = payload  # type: ignore[assignment]
            width = max(len(r) for r in rows)  # type: ignore[attr-defined]
            table = d.add_table(rows=0, cols=width)
            table.style = "Table Grid"
            for row in rows:  # type: ignore[attr-defined]
                cells = table.add_row().cells
                if len(row) == 1:  # section title / free line: one cell across the row
                    cells[0].merge(cells[-1])
                    _docx_runs(cells[0].paragraphs[0], row[0], bold=row[0].isupper())
                    continue
                for j, value in enumerate(row):
                    _docx_runs(cells[j].paragraphs[0], value, bold=value.endswith(":"))
        elif kind in ("ul", "ol"):
            for item in payload:  # type: ignore[attr-defined]
                # numbered items keep their source number as text; "List Number" would add a second
                _docx_runs(d.add_paragraph(style="List Bullet" if kind == "ul" else None), item)
        else:
            _docx_runs(d.add_paragraph(), str(payload))
    d.save(path)


def _pdf_text(pdf: FPDF, text: str, h: float, bold: bool = False) -> None:
    # bold by font switching, not fpdf's markdown mode: that would eat "--" and "__" in the text
    for i, line in enumerate(text.split("\n")):
        if i:
            pdf.ln(h)
        for seg, b in _segments(line):
            pdf.set_font(style="B" if bold or b else "")
            pdf.write(h, seg)
    pdf.ln(h)


def to_pdf(bl: list[Block], path: Path) -> None:
    pdf = FPDF(format="A4")
    pdf.set_margins(20, 20, 20)
    pdf.add_font("DejaVu", "", str(FONT_DIR / "DejaVuSans.ttf"))
    pdf.add_font("DejaVu", "B", str(FONT_DIR / "DejaVuSans-Bold.ttf"))
    pdf.add_page()
    for kind, payload in bl:
        size = {"h1": 15, "h2": 12.5, "h3": 11.5}.get(kind, 10.5)
        h = size * 0.5
        pdf.set_font("DejaVu", "", size)
        if kind == "table":
            with pdf.table(text_align="LEFT", line_height=h * 1.1) as table:
                for row_values in payload:  # type: ignore[attr-defined]
                    row = table.row()
                    for value in row_values:
                        row.cell(value)
        elif kind == "form":
            width = max(len(r) for r in payload)  # type: ignore[attr-defined]
            with pdf.table(
                text_align="LEFT",
                line_height=h * 1.1,
                first_row_as_headings=False,
                col_widths=(38, 62),
            ) as table:
                for row_values in payload:  # type: ignore[attr-defined]
                    row = table.row()
                    if len(row_values) == 1:
                        pdf.set_font(style="B" if row_values[0].isupper() else "")
                        row.cell(row_values[0], colspan=width)
                        pdf.set_font(style="")
                        continue
                    for j, value in enumerate(row_values):
                        span = width - len(row_values) + 1 if j == len(row_values) - 1 else 1
                        row.cell(value, colspan=span)
        elif kind in ("ul", "ol"):
            pdf.set_left_margin(25)
            for item in payload:  # type: ignore[attr-defined]
                pdf.set_x(25)
                _pdf_text(pdf, f"• {item}" if kind == "ul" else item, h)
            pdf.set_left_margin(20)
        else:
            _pdf_text(pdf, str(payload), h, bold=kind.startswith("h"))
        pdf.ln(size * 0.35)
    pdf.output(str(path))


def render(src: Path, out_dir: Path) -> None:
    text = src.read_text(encoding="utf-8")
    bl = blocks(text, form=src.name.startswith(FORM_PREFIX))
    stem = src.name.removesuffix(".md")
    (out_dir / f"{stem}.txt").write_text(to_txt(text), encoding="utf-8")
    to_docx(bl, out_dir / f"{stem}.docx")
    to_pdf(bl, out_dir / f"{stem}.pdf")


def main() -> None:
    corpus = Path(sys.argv[1])
    out_dir = corpus / "renders"
    out_dir.mkdir(exist_ok=True)
    srcs = sorted(f for sub in ("shareable", "link_only") for f in (corpus / sub).glob("*.md"))
    for f in srcs:
        render(f, out_dir)
    print(f"rendered {len(srcs)} documents × 3 formats into {out_dir}")


if __name__ == "__main__":
    main()
